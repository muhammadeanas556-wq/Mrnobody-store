// Generates supabase/seed.sql from src/data/demo.js
// Usage: npm run seed:sql
import { writeFileSync } from 'node:fs';
import { demoCategories, demoProducts, demoBanners, defaultSettings, defaultPages } from '../src/data/demo.js';

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

let sql = `-- MrNobody demo seed (generated by scripts/generate-seed.mjs)
-- All demo products/banners have is_demo = true. Delete them from Admin → Products
-- or run:  delete from products where is_demo; delete from banners where is_demo;

insert into public.site_settings (id, data) values (1, ${q(JSON.stringify(defaultSettings))}::jsonb)
on conflict (id) do nothing;

`;

for (const p of defaultPages) {
  sql += `insert into public.pages (slug, title, body) values (${q(p.slug)}, ${q(p.title)}, ${q(p.body)}) on conflict (slug) do nothing;\n`;
}
sql += '\n';

for (const c of demoCategories) {
  sql += `insert into public.categories (id, slug, name, description, image_url, position, is_visible) values (${q(c.id)}, ${q(c.slug)}, ${q(c.name)}, '', ${q(c.image_url)}, ${c.position}, true) on conflict (slug) do nothing;\n`;
}
sql += '\n';

for (const p of demoProducts) {
  sql += `insert into public.products (id, slug, name, description, category_id, price, compare_at_price, is_featured, is_new_arrival, is_best_seller, status, is_demo, sold_count, meta_title, meta_description, created_at) values (${[
    p.id, p.slug, p.name, p.description, p.category_id, p.price, p.compare_at_price, p.is_featured, p.is_new_arrival, p.is_best_seller, p.status, true, p.sold_count, p.meta_title, p.meta_description, p.created_at,
  ].map(q).join(', ')}) on conflict (slug) do nothing;\n`;
  for (const im of p.images) {
    sql += `insert into public.product_images (product_id, url, alt, position) values (${q(p.id)}, ${q(im.url)}, ${q(im.alt)}, ${im.position});\n`;
  }
  p.variants.forEach((v, i) => {
    sql += `insert into public.product_variants (id, product_id, sku, size, color, stock, position) values (${[v.id, p.id, v.sku, v.size, v.color, v.stock, i].map(q).join(', ')}) on conflict do nothing;\n`;
  });
}
sql += '\n';

for (const b of demoBanners) {
  const cols = ['id', 'placement', 'slot', 'position', 'eyebrow', 'title', 'subtitle', 'body', 'button_text', 'button_link', 'secondary_text', 'secondary_link', 'image_url', 'is_active', 'is_demo'];
  sql += `insert into public.banners (${cols.join(', ')}) values (${cols.map((k) => q(b[k] ?? null)).join(', ')}) on conflict do nothing;\n`;
}

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`seed.sql written: ${demoCategories.length} categories, ${demoProducts.length} products, ${demoBanners.length} banners`);
